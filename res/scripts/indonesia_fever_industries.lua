local industries = {}
function industries.isOwned(fileName)
	if type(fileName) ~= "string" then return false end
	local name = fileName:match("^res/construction/industry/([^/]+)%.con$")
		or fileName:match("^industry/([^/]+)%.con$")
	return name ~= nil and owned[name] == true
end
return industries
